#!/usr/bin/env python3
"""Generates main/f9p_config_data.h from the u-center ZED-F9P configuration dumps in tools/f9p/.

The dump is a u-center "Generation 9" configuration file: one CFG-VALGET response per line, as hex.
F9P_CFG holds the keys of the RS-232 config in file order, so the receiver is written in groups
of 64 keys like u-center does, minus every F9P UART2 key: this firmware only configures UART1 (and
USB) and leaves UART2 as it is. f9p_config.c changes a few of the remaining keys for this device.

Usage: tools/f9p_config_gen.py [--check]
  --check  only compare against the existing header, exit 1 if it is out of date
"""

import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DUMPS = ROOT / 'tools' / 'f9p'
OUTPUT = ROOT / 'main' / 'f9p_config_data.h'

RS232_FILE = 'F9P 1.13 Nav-PVT RS-232.txt'

EXPECTED_KEYS = 1212

# Key groups (bits 16-23) of CFG-UART2, CFG-UART2INPROT and CFG-UART2OUTPROT
UART2_GROUPS = {0x53, 0x75, 0x76}
MSGOUT_GROUP = 0x91

# Known CFG-MSGOUT UART2 keys (NMEA GGA, NMEA GSA, UBX NAV-SAT, UBX NAV-SIG), to check the classification
KNOWN_MSGOUT_UART2 = {0x209100BC, 0x209100C1, 0x20910017, 0x20910347}

# Value size in bytes from the key's size bits (28-30)
KEY_SIZES = {1: 1, 2: 1, 3: 2, 4: 4, 5: 8}


def parse(path):
    """Returns the firmware version and the (key, value) pairs in file order."""
    firmware = None
    items = []

    for line in path.read_text().splitlines():
        name, _, hex_bytes = line.partition(' - ')
        message = bytes(int(x, 16) for x in hex_bytes.split())
        length = message[2] | message[3] << 8
        payload = message[4:4 + length]

        if name.strip() == 'MON-VER':
            extensions = [payload[i:i + 30].split(b'\0')[0].decode() for i in range(40, len(payload), 30)]
            firmware = next((e[len('FWVER='):] for e in extensions if e.startswith('FWVER=')), None)
        elif name.strip() == 'CFG-VALGET':
            # version, layer, position, then key/value pairs
            i = 4
            while i < len(payload):
                key = int.from_bytes(payload[i:i + 4], 'little')
                size = KEY_SIZES[(key >> 28) & 7]
                value = int.from_bytes(payload[i + 4:i + 4 + size], 'little')
                items.append((key, value))
                i += 4 + size

    return firmware, items


def group(key):
    return (key >> 16) & 0xFF


def msgout_uart2_keys(items):
    """CFG-MSGOUT UART2 keys. The dump has no names, so they are found by position: every message has
    five keys with consecutive IDs, I2C, UART1, UART2, USB, SPI. In a run of consecutive IDs whose length
    is a multiple of five, the third key of every five is UART2. Runs of another length are left alone,
    as long as all their messages are off."""
    values = dict(items)
    keys = sorted(k for k in values if group(k) == MSGOUT_GROUP)

    runs = []
    for key in keys:
        if runs and key == runs[-1][-1] + 1:
            runs[-1].append(key)
        else:
            runs.append([key])

    uart2 = set()
    for run in runs:
        if len(run) % 5 == 0:
            uart2.update(run[2::5])
        elif any(values[k] for k in run):
            sys.exit(f'MSGOUT keys 0x{run[0]:08X}-0x{run[-1]:08X} cannot be split into ports and are not all off')

    missing = KNOWN_MSGOUT_UART2 - uart2
    if missing:
        sys.exit('MSGOUT UART2 classification missed ' + ', '.join(f'0x{k:08X}' for k in sorted(missing)))

    return uart2


def table(name, comment, items):
    lines = [f'// {comment}', f'static const f9p_cfg_item_t {name}[] = {{']
    for key, value in items:
        suffix = 'ull' if value > 0xFFFFFFFF else 'u'
        lines.append(f'        {{0x{key:08X}, {value}{suffix}}},')
    lines.append('};')
    return '\n'.join(lines)


def generate():
    firmware, items = parse(DUMPS / RS232_FILE)

    if len(items) != EXPECTED_KEYS:
        sys.exit(f'Expected {EXPECTED_KEYS} keys, found {len(items)}')

    uart2 = msgout_uart2_keys(items)
    kept = [(k, v) for k, v in items if group(k) not in UART2_GROUPS and k not in uart2]
    dropped = len(items) - len(kept)

    return f'''// Generated by tools/f9p_config_gen.py from the u-center configuration dump in tools/f9p/, do not edit.
// ZED-F9P firmware {firmware}, from {RS232_FILE}: {len(kept)} keys, {dropped} F9P UART2 keys left out

#ifndef ESP32_XBEE_F9P_CONFIG_DATA_H
#define ESP32_XBEE_F9P_CONFIG_DATA_H

#include <stdint.h>

typedef struct f9p_cfg_item {{
    uint32_t key;
    uint64_t value;
}} f9p_cfg_item_t;

{table('F9P_CFG', 'RS-232 config in file order, without the UART2 keys', kept)}

#endif //ESP32_XBEE_F9P_CONFIG_DATA_H
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true', help='exit 1 if the header is out of date')
    args = parser.parse_args()

    header = generate()

    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != header:
            sys.exit(f'{OUTPUT.relative_to(ROOT)} is out of date, run tools/f9p_config_gen.py')
        print(f'{OUTPUT.relative_to(ROOT)} is up to date')
    else:
        OUTPUT.write_text(header)
        print(f'Wrote {OUTPUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
